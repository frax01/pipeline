def shannon_entropy(s: str) -> float:
    """Calculate Shannon entropy of a string."""
    if not s:
        return 0.0
    freq = Counter(s)
    length = len(s)
    return -sum((count / length) * math.log2(count / length) for count in freq.values())


def is_valid_finding(finding: dict) -> bool:
    """Check that a finding has a valid ID (not corrupted evidence leaked into id)."""
    vid = finding.get("id", "")
    return isinstance(vid, str) and len(vid) < 50 and vid.isupper() and "_" in vid


