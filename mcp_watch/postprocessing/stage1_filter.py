# Magic parameters that are ACTUALLY used legitimately in many codebases
LEGITIMATE_MAGIC_PARAM_CONTEXTS = [
    # model_name is the most common false positive — used everywhere legitimately
    re.compile(r'def\s+\w*(?:test|mock|setup|create|init|build|get|set|format|validate|parse|config|load|save|register|log|display|show|render|generate_model|list_model|select_model|check_model)\w*\s*\(', re.IGNORECASE),
    # system_prompt used in legitimate prompt management
    re.compile(r'def\s+\w*(?:save|load|get|set|update|delete|create|format|validate|parse|render|display)_?system_?prompt\w*\s*\(', re.IGNORECASE),
    # Test files
    re.compile(r'(?:test_|_test\.py|\.test\.|\.spec\.|__test__|mock_|fixture)', re.IGNORECASE),
]


def filter_data_exfiltration_finding(finding: dict) -> tuple[bool, str]:
    """Filter data exfiltration findings."""
    vid = finding.get("id", "")
    evidence = finding.get("evidence", "") or ""
    filepath = finding.get("file", "") or ""

    if vid == "DATA_EXFILTRATION":
        # The json.dumps pattern is the biggest FP source — it flags ANY json.dumps
        # that mentions "prompt", "context", "tool", "history", "conversation"
        # But these words appear in legitimate data serialization constantly

        # Filter out third-party / vendored code
        if re.search(r'(?:node_modules|venv|\.venv|site-packages|vendor|dist|build)', filepath, re.IGNORECASE):
            return False, "third_party_code"

        # Filter out test files
        if re.search(r'(?:test|spec|mock|fixture|__test__|\.test\.|\.spec\.|/tests?/)', filepath, re.IGNORECASE):
            return False, "test_file"

        # Keep only if there's BOTH an HTTP outbound AND sensitive data keyword
        has_http_outbound = bool(re.search(
            r'(?:requests\.(?:post|put|patch)|fetch\s*\(|axios\.(?:post|put|patch)|'
            r'urllib\.request|http\.request)',
            evidence, re.IGNORECASE
        ))

        has_sensitive_data = bool(re.search(
            r'(?:conversation_history|system_prompt|chain_of_thought|'
            r'tool_call_history|session_data|internal_state)',
            evidence, re.IGNORECASE
        ))

        # json.dumps alone is NOT exfiltration — it's just serialization
        is_just_json_dumps = bool(re.search(r'^[^)]*json\.dumps?\s*\(', evidence))
        if is_just_json_dumps and not has_http_outbound:
            return False, "json_serialization_not_exfiltration"

        # base64.encode of sensitive data is suspicious even without HTTP
        has_encoding_of_sensitive = bool(re.search(
            r'base64\.(?:encode|b64encode)\s*\([^)]*(?:conversation|history|prompt|system)',
            evidence, re.IGNORECASE
        ))

        # system_prompt alone is NOT exfiltration — it's used in every LLM wrapper
        # Only keep if it's combined with an HTTP outbound or encoding
        is_system_prompt_only = bool(re.search(r'\bsystem_prompt\b', evidence)) and not bool(re.search(
            r'\b(?:conversation_history|tool_call_history|chain_of_thought|session_data|internal_state)\b',
            evidence
        ))

        # system_prompt in __init__, constructor, class definition, property, setter/getter
        if is_system_prompt_only and re.search(
            r'(?:def\s+__init__|def\s+(?:get|set|update|create|format|build|load|save|validate|parse|render)\w*\s*\(|'
            r'self\.system_prompt|this\.system_prompt|'
            r'class\s+\w+|constructor\s*\(|'
            r'system_prompt\s*[:=]\s*(?:str|string|None|null|""|\'\'|\[\]|Optional))',
            evidence, re.IGNORECASE
        ):
            return False, "system_prompt_in_constructor_or_setter"

        # system_prompt used in LLM call construction (generate, query, chat, complete, invoke)
        if is_system_prompt_only and re.search(
            r'(?:generate|query|chat|complete|invoke|call|send|create_message|_query_model|ask|run)\s*\(',
            evidence, re.IGNORECASE
        ):
            return False, "system_prompt_in_llm_call"

        if has_http_outbound and has_sensitive_data:
            return True, "http_exfiltration_of_sensitive_data"
        if has_encoding_of_sensitive:
            return True, "base64_encoding_of_sensitive_data"

        # HTTP outbound with generic keywords like "prompt", "tool" in the URL
        # is almost always a legitimate API call (e.g. /mcp/v1/tools/scan, PROMPT_GUARD_URL)
        # Only flag if the sensitive data keyword is in the PAYLOAD, not in the URL path
        if has_http_outbound:
            # Check if the keyword is in a variable being sent, not in the URL itself
            has_sensitive_in_payload = bool(re.search(
                r'(?:data|body|payload|json)\s*[:=]\s*.*(?:conversation|history|prompt|context)',
                evidence, re.IGNORECASE
            ))
            if has_sensitive_in_payload:
                # Exclude calls to security/guard/redaction services — they NEED the prompt to scan it
                if re.search(
                    r'(?:guard|redact|sanitize|filter|moderate|scan|check|validate|shield|safety|content.?policy|classify|virus.?total)',
                    evidence, re.IGNORECASE
                ):
                    return False, "security_service_call"
                # Exclude plugin/hook methods that just have 'payload' as a parameter name
                if re.search(r'(?:def|async def)\s+\w+\s*\(self,\s*payload\b', evidence):
                    return False, "plugin_hook_method"
                return True, "http_exfiltration_payload"
            return False, "http_call_keyword_in_url_only"

        # system_prompt without any outbound mechanism — just prompt handling code
        if is_system_prompt_only:
            return False, "system_prompt_without_exfiltration"

        return False, "no_exfiltration_pattern"

    elif vid == "MAGIC_PARAMETER_INJECTION":
        # Filter out third-party code
        if re.search(r'(?:node_modules|venv|\.venv|site-packages|vendor|dist|build)', filepath, re.IGNORECASE):
            return False, "third_party_code"

        # model_name is the #1 false positive — it's used in virtually every ML codebase
        # for legitimate model selection, not for magic parameter attacks
        if re.search(r'\bmodel_name\b', evidence) and not re.search(
            r'\b(?:conversation_history|tool_call_history|system_prompt|'
            r'chain_of_thought|every_single_previous_tool_call|all_tool_calls|'
            r'full_context|session_data|internal_state|debug_info)\b',
            evidence
        ):
            return False, "model_name_is_legitimate"

        # system_prompt in a function that manages prompts is legitimate
        if re.search(r'def\s+\w*(?:save|load|get|set|update|format|parse|render)_?\w*system_?prompt', evidence, re.IGNORECASE):
            return False, "prompt_management_function"

        # debug_info as a parameter is common in legitimate debugging
        if re.search(r'\bdebug_info\b', evidence) and not re.search(
            r'\b(?:conversation_history|system_prompt|tool_call_history)\b', evidence
        ):
            return False, "legitimate_debug_param"

        # Test files
        if re.search(r'(?:test_|_test\.py|\.test\.|\.spec\.|__test__|mock_|fixture|e2e)', filepath, re.IGNORECASE):
            return False, "test_file"

        # Magic parameter injection is about hidden params in TOOL DEFINITIONS (inputSchema)
        # that trick the LLM into sending data. Regular function parameters in code are NOT attacks.
        # Only flag if the parameter appears in a tool schema/definition context.
        truly_magic = [
            'conversation_history', 'tool_call_history', 'chain_of_thought',
            'every_single_previous_tool_call', 'all_tool_calls', 'full_context',
            'internal_state', 'tools_list'
        ]

        is_tool_schema = bool(re.search(
            r'(?:inputSchema|"properties"|"parameters"\s*:\s*\{|tool.*description|'
            r'register.*tool|add_tool|create_tool|Tool\s*\(|\.tool\s*\()',
            evidence, re.IGNORECASE
        ))

        for param in truly_magic:
            if param in evidence.lower().replace("-", "_").replace(" ", "_"):
                if is_tool_schema:
                    return True, f"magic_param_in_schema:{param}"
                # Regular function parameter — not an attack
                if re.search(r'(?:def\s+\w+\s*\(|async\s+def\s+\w+\s*\(|function\s+\w+\s*\()', evidence):
                    return False, f"regular_function_param:{param}"
                return True, f"magic_param:{param}"

        # system_prompt: only flag if it's in a TOOL DEFINITION (inputSchema, description)
        # NOT as a regular function parameter or method — it's used in every LLM wrapper
        if 'system_prompt' in evidence:
            # In a tool schema or description → suspicious (magic param attack)
            if re.search(r'(?:inputSchema|"properties"|"parameters"|tool.*description)', evidence, re.IGNORECASE):
                return True, "magic_param:system_prompt_in_tool_schema"
            # Regular function parameter, method, property → legitimate
            return False, "system_prompt_legitimate_usage"

        return False, "benign_parameter"

    elif vid == "UNUSED_SENSITIVE_PARAMETER":
        # This rule defaults to flagging when it can't find the function body
        # (which happens very often). Very high FP rate.
        # Only keep if the parameter is one of the truly dangerous magic params
        truly_magic = [
            'conversation_history', 'tool_call_history', 'chain_of_thought',
            'every_single_previous_tool_call', 'all_tool_calls', 'full_context',
        ]
        for param in truly_magic:
            if param in evidence.lower().replace("-", "_"):
                return True, f"unused_magic:{param}"

        # model_name, system_prompt, debug_info — too many legitimate uses
        return False, "common_parameter_name"

    elif vid == "CONVERSATION_EXFILTRATION_TRIGGER":
        # Filter out third-party code
        if re.search(r'(?:node_modules|venv|\.venv|site-packages|vendor|dist|build)', filepath, re.IGNORECASE):
            return False, "third_party_code"

        # Filter out test files
        if re.search(r'(?:test|spec|mock|fixture|__test__|\.test\.|\.spec\.|/tests?/)', filepath, re.IGNORECASE):
            return False, "test_file"

        # Tool descriptions that mention "private message", "DM", "personal" are
        # legitimate messaging tools, not exfiltration
        if re.search(r'(?:send\s+a\s+(?:private|direct)\s+message|DM|one-on-one|personal\s+(?:message|chat))', evidence, re.IGNORECASE):
            return False, "legitimate_messaging_tool"

        # Check if "description" is really a tool description with exfiltration language
        has_send_forward = bool(re.search(
            r'(?:forward|exfiltrate|steal|extract|leak|transmit)',
            evidence, re.IGNORECASE
        ))
        has_conversation = bool(re.search(
            r'(?:conversation\s+history|chat\s+history|message\s+history|all\s+(?:messages|conversations))',
            evidence, re.IGNORECASE
        ))
        if has_send_forward and has_conversation:
            return True, "exfiltration_in_description"

        # "Get details of a specific conversation" is a legitimate tool description
        if re.search(r'(?:get|list|fetch|retrieve|search|view|show|display|read)\s+(?:details?|info|data|messages?)\s+(?:of|from|about|for)', evidence, re.IGNORECASE):
            return False, "legitimate_conversation_tool"

        # description just mentions "history" or "conversation" without exfiltration intent
        return False, "no_exfiltration_intent"

    return False, "unknown_id"


# ═══════════════════════════════════════════════════════════════════════════
#  CATEGORY 4: PROTOCOL-VIOLATION
# ═══════════════════════════════════════════════════════════════════════════

def filter_protocol_violation_finding(finding: dict) -> tuple[bool, str]:
    """Filter protocol violation findings."""
    vid = finding.get("id", "")
    evidence = finding.get("evidence", "") or ""
    filepath = finding.get("file", "") or ""

    if vid == "INSECURE_TRANSPORT":
        # Already filters localhost/127.0.0.1/example.com, but still noisy

        # Filter out package-lock.json, package.json, lockfiles (license URLs, not code)
        if re.search(r'(?:package-lock\.json|package\.json|yarn\.lock|pnpm-lock|Pipfile\.lock|poetry\.lock|composer\.lock)', filepath, re.IGNORECASE):
            return False, "lockfile_or_manifest"

        # Filter out ALL data/config files — not executable code.
        # http:// URLs in these are references (HL7 FHIR, SNOMED, schemas, configs),
        # not code that makes insecure HTTP connections.
        if re.search(r'\.(?:json|yaml|yml|toml|ini|cfg|env|xml)$', filepath, re.IGNORECASE):
            return False, "data_config_file"

        # Filter out third-party / vendored code
        if re.search(r'(?:node_modules|venv|\.venv|site-packages|vendor|dist|build)', filepath, re.IGNORECASE):
            return False, "third_party_code"

        # Filter out test files
        if re.search(r'(?:test|spec|mock|fixture|__test__|__mock__|\.test\.|\.spec\.|/tests?/)', filepath, re.IGNORECASE):
            return False, "test_file"

        # Filter out comments
        if re.match(r'^\s*(?://|#|\*|/\*)', evidence):
            return False, "comment"

        # Filter out documentation / markdown files
        if re.search(r'\.(?:md|rst|txt|html|htm)$', filepath, re.IGNORECASE):
            return False, "documentation_file"

        # Filter out docs/ directories
        if re.search(r'(?:^|/)docs?/', filepath, re.IGNORECASE):
            return False, "docs_directory"

        # Filter out README content in JSON
        if re.search(r'"(?:Readme|ReadmeCN|description|readme)"', evidence, re.IGNORECASE):
            return False, "readme_content"

        # Filter out URLs with template variables (Python f-strings, JS template literals, etc.)
        # Catches: http://{settings.host}, http://${HOST}, http://{{host}}, http://$HOST
        if re.search(r'http://[^"]*(?:\{[a-zA-Z_]|\$[a-zA-Z_{]|\{\{)', evidence):
            return False, "template_variable_url"

        # Filter out common safe HTTP URLs (schemas, specs, namespaces, registries)
        safe_urls = [
            r'http://www\.w3\.org',
            r'http://schemas?\.',
            r'http://xmlns\.',
            r'http://purl\.org',
            r'http://json-schema\.org',
            r'http://www\.apache\.org',
            r'http://maven\.',
            r'http://creativecommons\.org',
            r'http://(?:www\.)?example\.',
            r'http://[a-zA-Z0-9_-]+\.github\.io',  # GitHub Pages (docs/licenses)
            r'http://www\.opengis\.net',             # OGC namespaces
            r'http://www\.idpf\.org',                # EPUB spec
            r'http://www\.color\.org',               # ICC color profiles
            r'http://ns\.',                          # XML namespaces
            r'http://www\.openarchives\.org',         # OAI
            r'http://ogp\.me',                        # Open Graph Protocol
            r'http://www\.sitemaps\.org',              # Sitemaps
            r'http://www\.rssboard\.org',              # RSS
            r'http://purl\.oclc\.org',                 # Dublin Core
            r'http://dbpedia\.org',                    # DBpedia
            r'http://www\.w3\.org',                    # W3C (already there but being thorough)
            r'http://rdfs?\.',                         # RDF schemas
            r'http://xmlns\.com',                      # XML namespaces
        ]
        for pattern in safe_urls:
            if re.search(pattern, evidence, re.IGNORECASE):
                return False, "safe_schema_url"

        # Filter out config for local services (common in MCP servers)
        # Includes hostnames without dots (internal services like "teradata-mcp-server")
        if re.search(r'http://(?:0\.0\.0\.0|host|hostname|\$)', evidence):
            return False, "local_config_variable"

        # Filter out internal service URLs (no dot in hostname = not a public domain)
        url_match = re.search(r'http://([^/:"\s]+)', evidence)
        if url_match:
            hostname = url_match.group(1)
            if '.' not in hostname:
                return False, "internal_service_hostname"

        # Filter out license/spec URLs in non-JSON files too
        if re.search(r'(?:license|licence|spdx)', evidence, re.IGNORECASE):
            return False, "license_url"

        # Filter out XML namespaces: {http://...} or xmlns="http://..."
        if re.search(r'(?:\{http://|xmlns\s*=\s*["\']http://)', evidence):
            return False, "xml_namespace"

        # Filter out URL validation / checking code (string literal used to test against)
        # e.g.: startsWith("http://"), .includes("http://"), === "http://", url.match("http://")
        if re.search(r'(?:startsWith|endsWith|includes|indexOf|match|test|search|replace|split)\s*\(\s*["\']http://', evidence):
            return False, "url_validation_code"

        # Filter out error messages / validation messages about URLs
        # e.g.: "must start with http://", "URL must be a valid URL starting with http://"
        if re.search(r'(?:must\s+(?:start|begin)|starting\s+with|invalid|expected|should\s+(?:start|begin)|format)\s*.*http://', evidence, re.IGNORECASE):
            return False, "url_validation_message"

        # Filter out console.error / console.log messages containing http://
        if re.search(r'console\.(?:error|warn|log|info)\s*\(.*http://', evidence):
            return False, "console_log_message"

        # Filter out string comparison / assignment of bare "http://" literal
        # e.g.: protocol === "http://", scheme = "http://", "must start with http://"
        if re.search(r'(?:["\']http://["\']|["\']https?://["\'])', evidence):
            return False, "protocol_string_literal"

        # Filter out SPARQL/RDF prefixes: PREFIX xxx: <http://...>
        if re.search(r'(?:PREFIX\s+\w*:\s*<http://|@prefix\s+)', evidence, re.IGNORECASE):
            return False, "sparql_rdf_prefix"

        # Filter out bundled/minified JS assets
        if re.search(r'(?:bundle|\.min\.|dist/|assets/scripts/|vendor\.)', filepath, re.IGNORECASE):
            return False, "bundled_js_asset"

        # Filter out description strings containing http:// links (documentation, not code)
        if re.search(r'(?:"description"|"summary"|"help"|"info"|"readme"|"text"|"message"|"detail"|"comment")\s*[:=]', evidence, re.IGNORECASE):
            return False, "description_string_with_link"

        # Filter out Python description= / help= keyword args with URLs
        if re.search(r'(?:description|help|message|detail|label|title|placeholder)\s*=\s*["\'].*http://', evidence, re.IGNORECASE):
            return False, "description_kwarg_with_link"

        # Filter out string concatenation/interpolation building URLs from variables
        # e.g.: `http://${host}:${port}`, "http://" + host
        if re.search(r'http://["\']?\s*\+\s*\w|http://\$\{|http://["\']?\s*\.\s*concat', evidence):
            return False, "dynamic_url_construction"

        # Filter out dictionary/object literal values — data, not HTTP connections
        # e.g.: 'source': 'http://...', "website": "http://...", "/RegistryName": "http://..."
        if re.search(r'["\'][^"\']*["\']\s*:\s*["\']http://', evidence):
            return False, "dict_value_not_connection"

        # Filter out http:// URLs used as dictionary KEYS (namespace maps, etc.)
        # e.g.: "http://www.opengis.net/wfs/2.0": {
        if re.search(r'["\']http://[^"\']+["\']\s*:', evidence):
            return False, "url_as_dict_key"

        # Filter out hardcoded URL strings assigned to variables or returned (reference data)
        # e.g.: return 'http://ws.audioscrobbler.com', BASE_URL = "http://..."
        if re.search(r'(?:return\s+|=\s*)["\']http://[^"\']+["\']', evidence):
            # Only keep if it's clearly making a connection (fetch, request, etc.)
            if not re.search(r'(?:fetch|request|axios|urllib|http\.get|http\.post|\.open\()', evidence):
                return False, "url_string_assignment"

        # Filter out docstrings / triple-quoted strings containing http://
        if re.search(r'(?:"""|\'\'\')', evidence):
            return False, "docstring_with_url"

        # Filter out string literals that are clearly documentation/help text
        # (long natural language strings with http:// in them)
        if re.search(r'(?:format|normalise|normalize|canonical|variant|convert|parse)\s.*http://', evidence, re.IGNORECASE):
            return False, "documentation_text_with_url"

        # Filter out security tool examples (nikto, nmap, etc.)
        if re.search(r'(?:nikto|nmap|burp|zap|sqlmap|metasploit|hydra)\s.*http://', evidence, re.IGNORECASE):
            return False, "security_tool_example"

        # Remaining http:// URLs to actual external services are real issues
        return True, "insecure_http_to_external"

    elif vid == "SESSION_ID_IN_URL":
        # Filter out README/documentation content
        if re.search(r'"(?:Readme|ReadmeCN|description)"', evidence, re.IGNORECASE):
            return False, "readme_content"

        # Filter out template placeholders
        if re.search(r'<UUID>|<session_id>|\{session_id\}|\$\{', evidence, re.IGNORECASE):
            return False, "template_placeholder"

        # Filter out comments
        if re.match(r'^\s*(?://|#|\*)', evidence):
            return False, "comment"

        # Filter out JSON data files
        if re.search(r'\.json$', filepath, re.IGNORECASE):
            return False, "json_data_file"

        # Filter out constructor/function calls where session_id is just a parameter
        # e.g.: McpSession(endpoint_url=..., session_id=session_id) — not a URL
        if re.search(r'(?:\w+\s*\(|new\s+\w+\s*\().*session_id\s*=', evidence) and not re.search(r'\?.*session_id=', evidence):
            return False, "constructor_parameter"

        # Filter out test files
        if re.search(r'(?:test|spec|mock|fixture|conftest|/tests?/)', filepath, re.IGNORECASE):
            return False, "test_file"

        # Actual session ID in URL construction (query string)
        if re.search(r'\?.*(?:sessionId|session_id|sid)=', evidence):
            return True, "session_id_in_url_construction"

        # session_id appended to URL path
        if re.search(r'(?:url|path|endpoint|route).*(?:sessionId|session_id|sid)=\$?\{?\w', evidence):
            return True, "session_id_in_url_construction"

        return False, "no_real_session_leak"

    return False, "unknown_id"


# ═══════════════════════════════════════════════════════════════════════════
#  CATEGORY 5: INPUT-VALIDATION
# ═══════════════════════════════════════════════════════════════════════════

def filter_input_validation_finding(finding: dict) -> tuple[bool, str]:
    """Filter input validation findings."""
    vid = finding.get("id", "")
    evidence = finding.get("evidence", "") or ""
    filepath = finding.get("file", "") or ""

    if vid == "COMMAND_INJECTION_RISK":
        # mcp-watch requires exec/spawn + user input keyword on same line
        # But "user", "input", "body", "params" appear in many safe contexts

        # Filter out third-party / vendored code (not the server's own code)
        if re.search(r'(?:node_modules|venv|\.venv|site-packages|vendor|dist|build|__pycache__|pip/_vendor)', filepath, re.IGNORECASE):
            return False, "third_party_code"

        # Filter out test files
        if re.search(r'(?:test|spec|mock|fixture|__test__|\.test\.|\.spec\.|/tests?/)', filepath, re.IGNORECASE):
            return False, "test_file"

        # Filter out regex.exec() — not command execution!
        # Includes /pattern/.exec(str) and named regex vars
        if re.search(r'\.exec\s*\(', evidence) and (
            re.search(r'(?:regex|Regex|RegExp|linkRegex|pattern|match)', evidence) or
            re.search(r'/[^/]+/\w*\.exec\s*\(', evidence)  # /pattern/.exec(str)
        ):
            return False, "regex_exec_not_command"

        # Filter out SQL/DB exec (not OS command injection, different vuln class)
        if re.search(r'(?:sql|SQL|\.exec\s*\(\s*["\'](?:SELECT|INSERT|UPDATE|DELETE|CREATE|DROP|ALTER))', evidence, re.IGNORECASE):
            return False, "sql_exec_not_command_injection"

        # Filter out DB/ORM .exec() — database query execution, not OS command
        if re.search(r'(?:query|statement|prepared|cursor|db|database|connection|conn|knex|sequelize|prisma|typeorm)\s*\.\s*exec', evidence, re.IGNORECASE):
            return False, "db_exec_not_command_injection"

        # Filter out CSS/style files — no command injection risk
        if re.search(r'\.(?:css|scss|sass|less)$', filepath, re.IGNORECASE):
            return False, "css_file"

        # Filter out description text and prompt examples (not actual code)
        if re.search(r'"description"', evidence, re.IGNORECASE):
            return False, "description_text"

        # Filter out example/documentation text (e.g. "if reviewer says 'change exec(userInput)'")
        if re.search(r'(?:example|e\.g\.|i\.e\.|says\s+"|change\s+`|reviewer|comment)', evidence, re.IGNORECASE):
            return False, "example_text"

        # Filter out prompt template strings
        if re.search(r'\.(?:ts|js)$', filepath) and re.search(r'(?:Example\s*-|`exec\()', evidence):
            return False, "prompt_template_text"

        # Filter out standard launcher scripts (spawn('node', [...process.argv]))
        # These pass through CLI args, not network user input
        if re.search(r'spawn\s*\(\s*["\']node["\']', evidence) and re.search(r'process\.argv', evidence):
            return False, "node_launcher_script"

        # Filter out rule description text / documentation strings (not actual code)
        if re.search(r'(?:Shell execution|Avoid\s+`|prefer\s+argument|strict\s+allowlist)', evidence, re.IGNORECASE):
            return False, "rule_description_text"

        # Filter out logger/monitoring methods that happen to have 'input' keyword nearby
        if re.search(r'(?:logger|log|monitor|analyze|report)\.\w+\s*\(', evidence, re.IGNORECASE):
            return False, "logging_not_execution"

        # Keep if it's genuinely exec/spawn with user-controlled input
        has_dangerous_exec = bool(re.search(
            r'(?:child_process|execSync|\bexec\b|spawn|\bsystem\b(?!\w)|popen|shell_exec|passthru)\s*\(',
            evidence
        ))
        has_user_input = bool(re.search(
            r'(?:req\.|params\.|query\.|body\.|input\.|args\.|user\w*Input)',
            evidence
        ))

        # argv is from process itself, not from network — lower risk
        has_only_argv = bool(re.search(r'argv', evidence)) and not has_user_input

        if has_dangerous_exec and has_user_input:
            return True, "command_injection_confirmed"

        if has_only_argv:
            return False, "process_argv_not_network_input"

        return False, "not_command_injection"

    elif vid == "SSRF_VULNERABILITY":
        # mcp-watch requires fetch/axios immediately followed by user input
        # This is already quite specific, but filter test/vendor files
        if re.search(r'(?:test|spec|mock|fixture|/tests?/)', filepath, re.IGNORECASE):
            return False, "test_file"
        if re.search(r'(?:node_modules|venv|\.venv|site-packages|vendor)', filepath, re.IGNORECASE):
            return False, "third_party_code"

        # Filter out database connection.fetch() — PostgreSQL asyncpg, not HTTP fetch
        if re.search(r'(?:connection|conn|pool|db|database|client|cursor)\s*\.\s*fetch', evidence, re.IGNORECASE):
            return False, "database_fetch_not_http"

        # Filter out ORM/DB query methods that look like fetch
        if re.search(r'(?:\.fetchone|\.fetchall|\.fetchmany|\.fetchval|\.fetchrow)\s*\(', evidence, re.IGNORECASE):
            return False, "database_fetch_method"

        # Filter out SDK/API .fetch() — Discord messages.fetch(), guild.stickers.fetch(), etc.
        if re.search(r'(?:messages?|channels?|guilds?|members?|users?|roles?|emojis?|reactions?|threads?|webhooks?|stickers?|bans?|invites?|pins?)\s*\.\s*fetch\s*\(', evidence, re.IGNORECASE):
            return False, "sdk_api_fetch_method"

        # Filter out any chained .something.fetch() on SDK objects (generic SDK pattern)
        if re.search(r'\.\w+\.\s*fetch\s*\(\s*(?:params|args|options|id|name)\b', evidence, re.IGNORECASE):
            return False, "sdk_chained_fetch"

        # Filter out CSS files — no SSRF from stylesheets
        if re.search(r'\.(?:css|scss|sass|less)$', filepath, re.IGNORECASE):
            return False, "css_file"

        # Filter out logger/monitor methods that happen to have 'request' and URL keywords
        if re.search(r'(?:logger|log)\.\w*(?:request|info|debug|warn)\s*\(', evidence, re.IGNORECASE):
            return False, "logging_not_fetch"

        # Filter out SDK client .request() — not direct HTTP fetch
        # e.g.: client.aiGateway.logs.request(), client.items.request()
        if re.search(r'(?:client|sdk|api|service)\.\w+(?:\.\w+)*\.request\s*\(', evidence, re.IGNORECASE):
            return False, "sdk_client_request"

        return True, "ssrf_pattern_confirmed"

    elif vid == "PATH_TRAVERSAL":
        # MASSIVE false positive source — matches any "../" including imports
        # Only keep if it's in a file read context with user input

        # Filter out import statements
        if re.search(r'(?:import|require|from)\s', evidence):
            return False, "import_statement"

        # Filter out relative path in string that's clearly a module reference
        if re.search(r'["\']\.\./', evidence) and re.search(r'(?:utils|lib|src|components|helpers|modules|services|config|types|interfaces)', evidence):
            return False, "module_relative_path"

        # Filter out comments
        if re.match(r'^\s*(?://|#|\*)', evidence):
            return False, "comment"

        # Filter out test files
        if re.search(r'(?:test|spec|mock|fixture)', filepath, re.IGNORECASE):
            return False, "test_file"

        # path.join with __dirname or __file__ and .. is static directory navigation
        if re.search(r'(?:path\.join|os\.path\.join)\s*\([^)]*(?:__dirname|__file__|os\.path\.dirname)', evidence):
            return False, "dirname_relative_navigation"

        # Keep only if there's a file operation with user-influenced path
        has_file_op = bool(re.search(r'(?:readFile|readdir|open|createReadStream|fs\.|path\.join)', evidence))
        has_user_input = bool(re.search(r'(?:req\.|params\.|query\.|body\.|input\.|args\.)', evidence))

        if has_file_op and has_user_input:
            return True, "path_traversal_with_user_input"

        return False, "static_relative_path"

    return False, "unknown_id"


