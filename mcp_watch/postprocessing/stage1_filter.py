CATEGORY_FILTERS = {
    "credential-leak": filter_credential_finding,
    "steganographic-attack": filter_steganographic_finding,
    "data-exfiltration": filter_data_exfiltration_finding,
    "protocol-violation": filter_protocol_violation_finding,
    "input-validation": filter_input_validation_finding,
}


def process_category(base_dir: Path, category: str, filter_fn) -> dict:
    """Process all JSON files in a category directory."""
    cat_dir = base_dir / category
    if not cat_dir.exists():
        print(f"  [SKIP] {category}/ not found")
        return {}

    json_files = sorted(cat_dir.glob("*.json"))
    if not json_files:
        print(f"  [SKIP] No JSON files in {category}/")
        return {}

    all_kept = []
    all_rejected = []
    stats_by_id = defaultdict(lambda: {"original": 0, "kept": 0, "rejected": 0, "reject_reasons": Counter()})
    total_original = 0
    total_kept = 0

    for json_file in json_files:
        # Skip existing filtered files
        if "filtered" in json_file.name or "refilter" in json_file.name:
            continue

        print(f"  Processing {json_file.name}...")

        with open(json_file, "r", encoding="utf-8") as f:
            data = json.load(f)

        findings = data.get("findings", [])
        severity = data.get("severity", "unknown")

        for finding in findings:
            if not is_valid_finding(finding):
                stats_by_id["_INVALID_ID"]["rejected"] += 1
                continue

            vid = finding["id"]
            stats_by_id[vid]["original"] += 1
            total_original += 1

            keep, reason = filter_fn(finding)

            if keep:
                finding["filter_confidence"] = reason
                all_kept.append(finding)
                stats_by_id[vid]["kept"] += 1
                total_kept += 1
            else:
                stats_by_id[vid]["rejected"] += 1
                stats_by_id[vid]["reject_reasons"][reason] += 1
                all_rejected.append({
                    "id": vid,
                    "reason": reason,
                    "evidence_preview": (finding.get("evidence", "") or "")[:80],
                    "server_name": finding.get("server_name", ""),
                })

    # Write filtered output
    filtered_dir = cat_dir / "filtered"
    filtered_dir.mkdir(exist_ok=True)

    output_file = filtered_dir / f"{category.replace('-', '_')}_filtered.json"
    output_data = {
        "category": category,
        "filter": "high_confidence_only",
        "filtered_at": datetime.now(timezone.utc).isoformat(),
        "original_total": total_original,
        "kept_total": total_kept,
        "rejection_rate": f"{((total_original - total_kept) / total_original * 100) if total_original > 0 else 0:.1f}%",
        "findings": all_kept,
    }

    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(output_data, f, indent=4, ensure_ascii=False)

    # Write stats
    stats_file = filtered_dir / f"{category.replace('-', '_')}_filter_stats.json"
    stats_data = {
        "category": category,
        "filtered_at": datetime.now(timezone.utc).isoformat(),
        "totals": {
            "original": total_original,
            "kept": total_kept,
            "rejected": total_original - total_kept,
            "rejection_rate": f"{((total_original - total_kept) / total_original * 100) if total_original > 0 else 0:.1f}%",
        },
        "by_vulnerability_id": {
            vid: {
                "original": info["original"],
                "kept": info["kept"],
                "rejected": info["rejected"],
                "rejection_rate": f"{(info['rejected'] / info['original'] * 100) if info['original'] > 0 else 0:.1f}%",
                "top_reject_reasons": dict(info["reject_reasons"].most_common(10)),
            }
            for vid, info in sorted(stats_by_id.items())
        },
    }

    with open(stats_file, "w", encoding="utf-8") as f:
        json.dump(stats_data, f, indent=4, ensure_ascii=False)

    print(f"    -> {total_kept:,} kept / {total_original:,} original ({output_data['rejection_rate']} rejected)")
    print(f"    -> Saved to {output_file.name}")

    return {
        "category": category,
        "original": total_original,
        "kept": total_kept,
        "rejected": total_original - total_kept,
    }


