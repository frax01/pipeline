def main():
    parser = argparse.ArgumentParser(description="Filter mcp-watch findings to high-confidence only")
    parser.add_argument("--input", "-i", type=Path, default=DEFAULT_BASE,
                        help="Base directory with category subdirectories")
    args = parser.parse_args()

    base_dir = args.input
    print(f"=" * 70)
    print(f"MCP-Watch High-Confidence Filter")
    print(f"Base directory: {base_dir}")
    print(f"=" * 70)

    global_stats = []

    for category, filter_fn in CATEGORY_FILTERS.items():
        print(f"\n{'─' * 50}")
        print(f"Category: {category}")
        print(f"{'─' * 50}")
        result = process_category(base_dir, category, filter_fn)
        if result:
            global_stats.append(result)

    # Write global summary
    print(f"\n{'=' * 70}")
    print(f"GLOBAL SUMMARY")
    print(f"{'=' * 70}")

    grand_original = sum(s["original"] for s in global_stats)
    grand_kept = sum(s["kept"] for s in global_stats)
    grand_rejected = grand_original - grand_kept

    summary = {
        "filter_run": datetime.now(timezone.utc).isoformat(),
        "grand_totals": {
            "original_findings": grand_original,
            "kept_findings": grand_kept,
            "rejected_findings": grand_rejected,
            "global_rejection_rate": f"{(grand_rejected / grand_original * 100) if grand_original > 0 else 0:.1f}%",
        },
        "per_category": global_stats,
    }

    summary_file = base_dir / "filter_global_summary.json"
    with open(summary_file, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=4, ensure_ascii=False)

    for s in global_stats:
        rej_pct = (s["rejected"] / s["original"] * 100) if s["original"] > 0 else 0
        print(f"  {s['category']:30s}  {s['kept']:>8,} kept / {s['original']:>10,} original  ({rej_pct:.1f}% rejected)")

    print(f"\n  {'TOTAL':30s}  {grand_kept:>8,} kept / {grand_original:>10,} original  "
          f"({(grand_rejected / grand_original * 100) if grand_original > 0 else 0:.1f}% rejected)")
    print(f"\n  Summary saved to: {summary_file}")


if __name__ == "__main__":
    main()
